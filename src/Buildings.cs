using System.Globalization;

namespace GEE;

/// <summary>One OSM building (or building part), reduced to boxes in meters east/north of (Lat, Lon).</summary>
public sealed class RawBuilding
{
    public long Id;
    public double Lat;
    public double Lon;
    /// <summary>Roof height above ground.</summary>
    public double Height;
    /// <summary>Bottom above ground, for parts that float such as overhangs; 0 stands on the ground.</summary>
    public double MinHeight;
    public int Variant;
    public List<Box2> Boxes = new();
    /// <summary>Window pattern of the facade (Buildings.Style*).</summary>
    public int Style;
    /// <summary>Gabled roof on top of Height, ridge along the longer side; 0 is a flat roof.</summary>
    public double RoofHeight;
    public int RoofVariant;
    /// <summary>Roof slope in radians (Roof* above): every box of the building gets a roof of its own height at this pitch.</summary>
    public double RoofPitch;
    /// <summary>Hipped instead of gabled: the roof shape is picked per box from its proportions (Placement.MakeRoof).</summary>
    public bool RoofHip;
    /// <summary>Flat ground surface such as an apron, laid on the terrain instead of standing on it.</summary>
    public bool Slab;
    /// <summary>Part of a modelled launch complex (landmark, pipeline, structure from data), not a plain OSM building.</summary>
    public bool LaunchComplex;
}

public sealed class OsmOptions
{
    public double PlanetRadius = 6371000;
    public int MaxSplitDepth = 3;
    public double MinFill = 0.8;
}

