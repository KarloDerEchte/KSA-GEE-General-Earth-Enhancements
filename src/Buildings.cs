using System.Globalization;

namespace GEE;

/// <summary>One OSM building (or building part), reduced to boxes in meters east/north of (Lat, Lon).</summary>
public sealed class RawBuilding
{
    public long Id;
    public double Lat;
    public double Lon;
    /// <summary>Roof height above ground.</summary>
    public double Height;
    /// <summary>Bottom above ground, for parts that float such as overhangs; 0 stands on the ground.</summary>
    public double MinHeight;
    public int Variant;
    public List<Box2> Boxes = new();
    /// <summary>Window pattern of the facade (Buildings.Style*).</summary>
    public int Style;
    /// <summary>Gabled roof on top of Height, ridge along the longer side; 0 is a flat roof.</summary>
    public double RoofHeight;
    public int RoofVariant;
    /// <summary>Flat ground surface such as an apron, laid on the terrain instead of standing on it.</summary>
    public bool Slab;
    /// <summary>Part of a modelled launch complex (landmark, pipeline, structure from data), not a plain OSM building.</summary>
    public bool LaunchComplex;
}

public sealed class OsmOptions
{
    public double PlanetRadius = 6371000;
    public int MaxSplitDepth = 3;
    public double MinFill = 0.8;
}

/// <summary>Turns building outlines into RawBuildings. Kept free of game types so it can be tested offline.</summary>
public static class Buildings
{
    /// <summary>
    /// Facade colours of the building variants, in the same order as the materials in Assets.xml
    /// (generated by tools/make_assets.py, which holds the same table).
    /// </summary>
    public static readonly (string Name, int R, int G, int B)[] Variants =
    {
        ("concrete", 178, 176, 170),
        ("plaster", 222, 218, 208),
        ("sand", 205, 185, 150),
        ("brick", 150, 80, 60),
        ("dark", 95, 98, 104),
        ("glass", 110, 135, 160),
        ("metal", 185, 190, 195),
        ("ochre", 210, 170, 100),
    };

    /// <summary>Material index of the road asset, after the building variants.</summary>
    public const int RoadVariant = 8;
    /// <summary>Material index of the first landmark model (Landmarks.All), after the road.</summary>
    public const int FirstLandmarkVariant = 9;
    /// <summary>Gabled roofs (tile red, slate, brown), after the landmarks.</summary>
    public static readonly int FirstRoofVariant = FirstLandmarkVariant + Landmarks.All.Length;
    public const int RoofVariants = 3;
    /// <summary>Airfield surfaces, after the roofs.</summary>
    public static readonly int RunwayVariant = FirstRoofVariant + RoofVariants;
    public static readonly int TaxiwayVariant = RunwayVariant + 1;
    public static readonly int ApronVariant = RunwayVariant + 2;
    /// <summary>Round tanks and silos, after the airfield surfaces.</summary>
    public static readonly int TankVariant = ApronVariant + 1;
    /// <summary>Domed top of a tank, same material as the tank.</summary>
    public static readonly int TankCapVariant = TankVariant + 1;
    /// <summary>A tank lying down (the long propellant tanks), and the payload tent's arch.</summary>
    public static readonly int HorizontalTankVariant = TankCapVariant + 1;
    public static readonly int TentVariant = TankCapVariant + 2;
    /// <summary>Low-pitched standing-seam metal roof for halls (gable mesh).</summary>
    public static readonly int MetalRoofVariant = TentVariant + 1;
    /// <summary>The swinging crew access arm of LC-39A (CrewArm).</summary>
    public static readonly int CrewArmVariant = MetalRoofVariant + 1;
    /// <summary>Main road asphalt without lines, laid where roads meet (RoadJunctions, RawRoad.Clear).</summary>
    public static readonly int RoadPlainVariant = CrewArmVariant + 1;
    /// <summary>One-way motorway and trunk carriageways: Poly Haven asphalt scan with shoulder, lanes and edge lines.</summary>
    public static readonly int HighwayVariant = RoadPlainVariant + 1;
    /// <summary>Unmarked streets and one-lane ramps with edge lines, from the same scan.</summary>
    public static readonly int StreetVariant = HighwayVariant + 1;
    public static readonly int RampVariant = StreetVariant + 1;
    /// <summary>Tracks and unpaved roads: dirt scan.</summary>
    public static readonly int TrackVariant = RampVariant + 1;
    /// <summary>Estimated lane counts (OMT has no lanes tag, see Roads.Classify): three-lane one-way motorway carriageway, four-lane two-way trunk/motorway drawn as one line.</summary>
    public static readonly int Highway3Variant = TrackVariant + 1;
    public static readonly int Highway4Variant = Highway3Variant + 1;
    /// <summary>Ramp surface with chevron hatching, for the tapered merge stretch (RoadGore).</summary>
    public static readonly int GoreVariant = Highway4Variant + 1;
    /// <summary>Solid white paint slab for crosswalk stripes and stop lines (JunctionMarkings), same scan mesh as the roads.</summary>
    public static readonly int JunctionPaintVariant = GoreVariant + 1;
    /// <summary>Roadside furniture (RoadFurniture, tools/furniture_assets.py): street lamp, post sign, sign gantry.</summary>
    public static readonly int FurnitureVariant = JunctionPaintVariant + 1;
    public const int FurnitureModels = 3;
    public static readonly int VariantCount = FurnitureVariant + FurnitureModels;

    public static int SurfaceVariant(RoadSurface surface) => surface switch
    {
        RoadSurface.Highway => HighwayVariant,
        RoadSurface.Highway3 => Highway3Variant,
        RoadSurface.Highway4 => Highway4Variant,
        RoadSurface.Street => StreetVariant,
        RoadSurface.Ramp => RampVariant,
        RoadSurface.Track => TrackVariant,
        _ => RoadVariant,
    };

    /// <summary>The surface without lines, for the stretches where roads meet.</summary>
    public static int PlainVariant(RoadSurface surface) => surface switch
    {
        RoadSurface.Street => StreetVariant,
        RoadSurface.Track => TrackVariant,
        _ => RoadPlainVariant,
    };

    /// <summary>Road pieces (not airfield surfaces): these get street lamps.</summary>
    public static bool IsStreetSurface(int variant) =>
        variant == RoadVariant || variant == RoadPlainVariant || variant == HighwayVariant || variant == Highway3Variant || variant == Highway4Variant || variant == StreetVariant
        || variant == RampVariant || variant == TrackVariant || variant == GoreVariant;
    /// <summary>Facades of plant and support buildings: concrete, metal, concrete.</summary>
    public static readonly int[] CompoundVariants = { 0, 6, 0 };

    /// <summary>Window patterns, see FacadeTechnique.</summary>
    public const int StyleResidential = 0, StyleOffice = 1, StyleIndustrial = 2, StyleNone = 3;
    /// <summary>Launch complex buildings: corrugated metal hall, concrete utility shelter, office with ribbon windows.</summary>
    public const int StyleMetalHall = 4, StyleShelter = 5, StyleRibbon = 6;

    /// <summary>OpenMapTiles gives 5 m when OSM has neither a height nor levels.</summary>
    private const double UnknownHeight = 5;

    public static RawBuilding? FromRing(long id, List<(double Lat, double Lon)> ring, double height, double minHeight, string? colour, OsmOptions options)
    {
        if (ring.Count > 1 && ring[0] == ring[^1])
            ring.RemoveAt(ring.Count - 1);
        if (ring.Count < 3)
            return null;

        double lat0 = ring.Average(p => p.Lat);
        double lon0 = ring.Average(p => p.Lon);
        double k = Math.PI / 180 * options.PlanetRadius;
        double kLon = k * Math.Cos(lat0 * Math.PI / 180);
        var outline = new List<Footprint.P>(ring.Count);
        foreach (var (lat, lon) in ring)
            outline.Add(new Footprint.P((lon - lon0) * kLon, (lat - lat0) * k));

        double area = Math.Abs(Footprint.SignedArea(outline));
        if (area < 4)
            return null;
        var round = RoundOutline(outline, area);
        var boxes = round is { } disc
            ? new List<Box2> { new(disc.X, disc.Y, 0, 2 * disc.Radius, 2 * disc.Radius) }
            : Footprint.Decompose(outline, options.MaxSplitDepth, options.MinFill);
        if (boxes.Count == 0)
            return null;

        // Same id for pieces of one building in neighbouring tiles, so they pick the same colour.
        long seed = id != 0 ? id : BitConverter.DoubleToInt64Bits(Math.Round(lat0, 4) * 7 + Math.Round(lon0, 4));
        bool estimated = height <= 0 || (Math.Abs(height - UnknownHeight) < 1e-6 && minHeight <= 0);
        if (estimated)
            height = round is { } tank ? Math.Clamp(2.2 * tank.Radius * (0.8 + 0.4 * Unit(seed ^ 0x5bd1e995)), 4, 26)
                : EstimateHeight(area, Unit(seed ^ 0x5bd1e995));
        int variant = round != null ? TankVariant : Variant(seed, colour, height, area);
        var building = new RawBuilding
        {
            Id = id,
            Lat = lat0,
            Lon = lon0,
            Height = Math.Clamp(height, 2.5, 900),
            MinHeight = Math.Clamp(minHeight, 0, Math.Max(height - 1, 0)),
            Variant = variant,
            Boxes = boxes,
            Style = round != null ? StyleNone : height > 30 || variant == 5 ? StyleOffice : height < 14 && area > 1500 ? StyleIndustrial : StyleResidential,
        };

        // Houses get a pitched roof of 28-42 degrees over the short side; the walls lose what the roof takes.
        if (round == null && boxes.Count == 1 && minHeight <= 0 && area is > 30 and < 350 && height <= 13 && variant is 1 or 2 or 3 or 7)
        {
            Box2 box = boxes[0];
            double pitch = (28 + 14 * Unit(seed ^ 0x2545f491)) * Math.PI / 180;
            double roof = Math.Tan(pitch) * Math.Min(box.LengthA, box.LengthB) / 2;
            building.RoofHeight = roof;
            building.Height = Math.Max(building.Height - (estimated ? 0 : roof), 2.6);
            {
                double ur = Unit(seed ^ 0x68e31da4); // tile red 15%, slate 45%, brown 40%
                building.RoofVariant = FirstRoofVariant + (ur < 0.15 ? 0 : ur < 0.60 ? 1 : 2);
            }
        }
        return building;
    }

    /// <summary>
    /// A closed outline that is a circle (tanks, silos, gasometers): at least 10 corners, all about one radius from
    /// the centre and the area of that circle. Pieces cut by a tile edge are not round and stay boxes.
    /// </summary>
    internal static (double X, double Y, double Radius)? RoundOutline(List<Footprint.P> outline, double area)
    {
        if (outline.Count < 10 || area < 12)
            return null;
        double cx = outline.Average(p => p.X), cy = outline.Average(p => p.Y);
        double radius = outline.Average(p => Math.Sqrt(Sq(p.X - cx) + Sq(p.Y - cy)));
        if (radius < 2 || outline.Any(p => Math.Abs(Math.Sqrt(Sq(p.X - cx) + Sq(p.Y - cy)) - radius) > 0.08 * radius))
            return null;
        return Math.Abs(area / (Math.PI * radius * radius) - 1) < 0.12 ? (cx, cy, radius) : null;
    }

    /// <summary>
    /// Wall height for outlines without a height: footprint size says roughly what a building is, u in [0, 1)
    /// varies it per building.
    /// </summary>
    internal static double EstimateHeight(double area, double u) => area switch
    {
        < 50 => 2.6 + 1.0 * u,     // sheds, garages
        < 250 => 3.0 + 3.2 * u,    // houses, one or two floors (the roof comes on top)
        < 1000 => 6.0 + 9.0 * u,   // small apartment blocks, shops
        < 4000 => 8.0 + 14.0 * u,  // apartment blocks, offices
        _ => 7.0 + 7.0 * u,        // halls, warehouses, malls
    };

    internal static int Variant(long seed, string? colour, double height, double area)
    {
        if (ParseColour(colour) is { } c)
        {
            int best = 0;
            double bestDist = double.MaxValue;
            for (int i = 0; i < Variants.Length; i++)
            {
                var v = Variants[i];
                double d = Sq(v.R - c.R) + Sq(v.G - c.G) + Sq(v.B - c.B);
                if (d < bestDist) { bestDist = d; best = i; }
            }
            return best;
        }

        // The tiles carry no building type, so guess from the shape: towers are modern, big low halls industrial.
        int[] choices = height > 35 ? new[] { 0, 4, 5, 1 }
            : height < 14 && area > 1500 ? new[] { 6, 0, 4 }
            : new[] { 1, 2, 3, 7, 0, 0, 1, 2, 0, 3 }; // roofs: terracotta only on ochre (1 in 10)
        return choices[(int)(Unit(seed) * choices.Length) % choices.Length];
    }

    private static double Sq(double x) => x * x;

    /// <summary>Deterministic value in [0, 1) per building, so colours stay the same between sessions.</summary>
    private static double Unit(long seed)
    {
        ulong x = ((ulong)seed + 0x9E3779B97F4A7C15UL) * 0xBF58476D1CE4E5B9UL;
        x ^= x >> 31;
        return (x >> 11) * (1.0 / (1UL << 53));
    }

    private static (int R, int G, int B)? ParseColour(string? s)
    {
        if (string.IsNullOrWhiteSpace(s))
            return null;
        s = s.Trim().ToLowerInvariant();
        if (s.StartsWith('#') && s.Length == 7 && int.TryParse(s.AsSpan(1), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out int rgb))
            return ((rgb >> 16) & 255, (rgb >> 8) & 255, rgb & 255);
        if (s.StartsWith('#') && s.Length == 4 && int.TryParse(s.AsSpan(1), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out int short3))
            return (((short3 >> 8) & 15) * 17, ((short3 >> 4) & 15) * 17, (short3 & 15) * 17);
        return s switch
        {
            "white" or "ivory" or "snow" => (235, 235, 230),
            "grey" or "gray" or "silver" or "lightgrey" or "lightgray" => (170, 170, 170),
            "darkgrey" or "darkgray" or "black" or "dimgray" or "dimgrey" => (80, 80, 85),
            "red" or "darkred" or "maroon" or "firebrick" => (160, 60, 50),
            "brown" or "sienna" or "saddlebrown" => (130, 85, 60),
            "beige" or "tan" or "wheat" or "cream" or "linen" => (210, 190, 155),
            "yellow" or "gold" or "khaki" or "lightyellow" => (220, 190, 100),
            "orange" or "coral" or "salmon" or "peru" => (215, 140, 80),
            "pink" or "mistyrose" => (225, 175, 170),
            "blue" or "lightblue" or "steelblue" or "skyblue" or "navy" => (110, 135, 170),
            "green" or "olive" or "darkgreen" => (110, 140, 100),
            _ => null,
        };
    }
}
